"""Generate repository-owned synthetic fixtures; no network or personal input.

Run manually with Python 3 and ffmpeg. The committed bytes, not the local codec
installation, are the test inputs. SOURCE.json pins their hashes.
"""

import hashlib
import json
import math
import struct
import subprocess
import wave
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def png(name, colors, alpha=False):
    width, height = 256, 128
    def chunk(kind, value):
        return struct.pack(">I", len(value)) + kind + value + struct.pack(">I", zlib.crc32(kind + value))
    raw = b"".join(b"\0" + b"".join(bytes(colors[x >= width // 2]) for x in range(width)) for _ in range(height))
    header = struct.pack(">IIBBBBB", width, height, 8, 6 if alpha else 2, 0, 0, 0)
    (ROOT / name).write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


png("red-blue.png", [(255, 0, 0), (0, 0, 255)])
png("green-yellow.png", [(0, 192, 0), (255, 255, 0)])
png("edit-mask.png", [(0, 0, 0, 0), (0, 0, 0, 255)], alpha=True)

with wave.open(str(ROOT / "two-beeps.wav"), "wb") as output:
    output.setnchannels(1)
    output.setsampwidth(2)
    output.setframerate(16000)
    samples = []
    for index in range(32000):
        second = index / 16000
        active = 0.2 <= second < 0.5 or 1.1 <= second < 1.4
        samples.append(struct.pack("<h", round(10000 * math.sin(2 * math.pi * 1000 * second)) if active else 0))
    output.writeframes(b"".join(samples))

subprocess.run([
    "ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
    "-f", "lavfi", "-i", "color=c=red:s=256x128:r=2:d=1",
    "-f", "lavfi", "-i", "color=c=blue:s=256x128:r=2:d=1",
    "-filter_complex", "[0:v][1:v]concat=n=2:v=1:a=0,format=yuv420p[v]",
    "-map", "[v]", "-an", "-c:v", "libx264", "-preset", "veryfast",
    "-crf", "18", "-movflags", "+faststart", "-map_metadata", "-1",
    "-fflags", "+bitexact", str(ROOT / "red-then-blue.mp4"),
], check=True)

objects = [
    b"<< /Type /Catalog /Pages 2 0 R >>",
    b"<< /Type /Pages /Kids [3 0 R 5 0 R] /Count 2 >>",
    b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 7 0 R >> >> /Contents 4 0 R >>",
    b"",
    b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 7 0 R >> >> /Contents 6 0 R >>",
    b"",
    b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
]
for index, sentence in [(3, "The notebook code is SAPPHIRE-731."), (5, "The delivery code is ORCHID-264.")]:
    data = f"BT /F1 24 Tf 60 700 Td ({sentence}) Tj ET\n".encode("ascii")
    objects[index] = b"<< /Length " + str(len(data)).encode("ascii") + b" >>\nstream\n" + data + b"endstream"
pdf = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
offsets = [0]
for index, value in enumerate(objects, 1):
    offsets.append(len(pdf))
    pdf.extend(f"{index} 0 obj\n".encode("ascii") + value + b"\nendobj\n")
xref = len(pdf)
pdf.extend(f"xref\n0 {len(offsets)}\n0000000000 65535 f \n".encode("ascii"))
for offset in offsets[1:]:
    pdf.extend(f"{offset:010} 00000 n \n".encode("ascii"))
pdf.extend(f"trailer\n<< /Size {len(offsets)} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode("ascii"))
(ROOT / "two-pages.pdf").write_bytes(pdf)

files = {}
for filename in ["red-blue.png", "green-yellow.png", "edit-mask.png", "two-beeps.wav", "red-then-blue.mp4", "two-pages.pdf"]:
    data = (ROOT / filename).read_bytes()
    files[filename] = {"sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}
(ROOT / "SOURCE.json").write_text(json.dumps({
    "source": "Repository-owned synthetic fixtures; generated by generate.py without network or personal data.",
    "attribution": "Generated without third-party media or fonts; repository terms apply.",
    "content": {"image": "red/blue and green/yellow panels", "mask": "transparent left, opaque right", "audio": "two 1000 Hz bursts in two seconds", "video": "red for one second, then blue for one second", "pdf": "two pages containing independent synthetic codes"},
    "files": files,
}, indent=2) + "\n")
