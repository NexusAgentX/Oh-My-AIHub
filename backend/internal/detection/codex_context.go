const codexMissingNote = "AIHUB-SYNTHETIC-NOTE-MISSING"

func (n *nativeScene) codexContextModel(ctx context.Context) string {
	if n.s.Target.Model != "" {
		return n.s.Target.Model
	}
	out, _ := n.codexCatalog(ctx)
	for _, raw := range list(out.Reply.Object["models"]) {
		if slug := str(object(raw)["slug"]); gatewaycontract.ValidModelID(slug) {
			return slug
		}
	}
	return ""
}

func (n *nativeScene) codexContextCall(ctx context.Context, session, namespace, operation string, args nativeObject) nativeOutcome {
	body := cloneNative(args)
	body["context"] = nativeObject{"session_id": session, "current_agent_name": "/root"}
	headers := http.Header{"Content-Type": {"application/json"}, "Session-Id": {session}, "X-Openai-Tool-Output-Truncation-Policy": {`{"mode":"bytes","limit":4000}`}}
	if operation == "search_contents" || operation == "write_file" || operation == "append_to_file" {
		headers.Set("X-Openai-Encrypted-Tool-Arguments", "true")
	}
	return n.call(ctx, Request{EndpointID: "codex." + namespace + "." + operation, Path: "/backend-api/codex/alpha/" + namespace + "/v2/" + operation, Headers: headers, Body: mustNativeJSON(body), Category: "query"}, false)
}

// Encrypted tool arguments are generated by the actual model, as in the pinned
// CLI. The detector never invents ciphertext or strips the encrypted annotation.
func (n *nativeScene) codexContextArguments(ctx context.Context, model, session, operation string, desired nativeObject) (nativeObject, nativeOutcome) {
	return n.codexContextArgumentsFor(ctx, model, session, "notes", operation, desired)
}

func (n *nativeScene) codexContextArgumentsFor(ctx context.Context, model, session, namespace, operation string, desired nativeObject) (nativeObject, nativeOutcome) {
	properties, required := nativeObject{}, []any{}
	for name := range desired {
		property := nativeObject{"type": "string"}
		if name == "text" || name == "query" {
			property["encrypted"] = true
		}
		properties[name], required = property, append(required, name)
	}
	slices.SortFunc(required, func(a, b any) int { return strings.Compare(str(a), str(b)) })
	body := codexBase(model)
	if _, err := n.codexContextInitialize(body, model, session); err != nil {
		return nil, nativeOutcome{State: "inconclusive", Reason: "detector_error"}
	}
	body["input"] = []any{nativeObject{"role": "user", "content": "Call only " + namespace + "." + operation + " on this isolated synthetic context, using these exact values. Preserve the required encrypted argument representation. Do not invent a result: " + string(mustNativeJSON(desired))}}
	body["tools"] = []any{nativeObject{"type": "namespace", "name": namespace, "description": "Isolated synthetic context tools.", "tools": []any{nativeObject{"type": "function", "name": operation, "description": "Isolated synthetic context capability probe.", "parameters": nativeObject{"type": "object", "properties": properties, "required": required, "additionalProperties": false}}}}}
	body["tool_choice"] = "required"
	out := n.codexInfer(ctx, body, "")
	if out.State != "pass" || len(out.Reply.Candidates) != 1 || len(out.Reply.Candidates[0].Calls) != 1 {
		return nil, out
	}
	call := out.Reply.Candidates[0].Calls[0]
	if call.Namespace != namespace || call.Name != operation || call.ID == "" || len(call.Arguments) != len(desired) {
		return nil, out
	}
	for name, value := range desired {
		actual := str(call.Arguments[name])
		if actual == "" || len(actual) > 64<<10 || ((name != "query" && name != "text") && actual != str(value)) {
			return nil, out
		}
	}
	return call.Arguments, out
}

func codexContextValue(out nativeOutcome) any {
	if v, exists := out.Reply.Object["context_result"]; exists {
		return v
	}
	return out.Reply.Object
}

func codexContextOutput(value any) (any, bool) {
	root := object(value)
	var images any
	hasImages := false
	if root != nil {
		copy := nativeObject{}
		for key, field := range root {
			if key == "images" {
				images = field
				hasImages = true
			} else {
				copy[key] = field
			}
		}
		value, root = copy, copy
	}
	content := []any{}
	text := string(mustNativeJSON(value))
	if encrypted := str(root["encrypted_output"]); encrypted != "" {
		content = append(content, nativeObject{"type": "encrypted_content", "encrypted_content": encrypted})
	} else if !hasImages {
		return text, true
	} else {
		content = append(content, nativeObject{"type": "input_text", "text": text})
	}
	if hasImages {
		rows, ok := images.([]any)
		if !ok || len(rows) > 32 {
			return nil, false
		}
		for _, raw := range rows {
			image := object(raw)
			mime, data := str(image["mime_type"]), str(image["data"])
			if !strings.HasPrefix(mime, "image/") || len(mime) > 128 || strings.ContainsAny(mime, ";,\r\n\x00") || data == "" {
				return nil, false
			}
			item := nativeObject{"type": "input_image", "image_url": "data:" + mime + ";base64," + data}
			if detail, exists := image["detail"]; exists && detail != nil {
				if !slices.Contains([]string{"auto", "low", "high", "original"}, str(detail)) {
					return nil, false
				}
				item["detail"] = detail
			}
			content = append(content, item)
		}
	}
	return content, true
}

func (n *nativeScene) codexContextText(ctx context.Context, model, session, namespace, operation, instruction string, args nativeObject, result nativeOutcome) nativeOutcome {
	if result.State != "pass" {
		return result
	}
	output, valid := codexContextOutput(codexContextValue(result))
	if !valid {
		result.State, result.Reason = "fail", "invalid_response"
		return result
	}
	body := codexBase(model)
	body["client_metadata"] = nativeObject{"session_id": session}
	missing := " If no note exists return exactly " + codexMissingNote + "."
	if namespace == "history" {
		missing = " If the requested history is absent return exactly {}."
	}
	body["input"] = []any{
		nativeObject{"role": "user", "content": instruction + " Use only the actual returned tool result." + missing},
		nativeObject{"type": "function_call", "namespace": namespace, "name": operation, "call_id": "aihub-context-result", "arguments": string(mustNativeJSON(args))},
		nativeObject{"type": "function_call_output", "call_id": "aihub-context-result", "output": output},
	}
	return n.codexInfer(ctx, body, "")
}

func (n *nativeScene) codexNotes(ctx context.Context) {
	model := n.codexContextModel(ctx)
	if model == "" {
		return // actual catalog prerequisite remains in the result witnesses
	}
	session, err := ids.NewUUID()
	if err != nil {
		n.codexContextDetectorError()
		return
	}
	other, err := ids.NewUUID()
	if err != nil {
		n.codexContextDetectorError()
		return
	}
	path := "aihub-probe-" + session + ".txt"
	marker, appended := "AIHUB synthetic note "+other, "APPEND-"+session
	writeArgs, generated := n.codexContextArguments(ctx, model, session, "write_file", nativeObject{"path": path, "text": marker})
	if writeArgs == nil {
		n.check("write_file", generated, false)
		return
	}
	write := n.codexContextCall(ctx, session, "notes", "write_file", writeArgs)
	readArgs := nativeObject{"path": path}
	read := n.codexContextCall(ctx, session, "notes", "read_file", readArgs)
	text := n.codexContextText(ctx, model, session, "notes", "read_file", "Return only the full actual note text, without labels or formatting.", readArgs, read)
	valid := write.State == "pass" && read.State == "pass" && contentMatches(text, marker) && nativeEndedNormally(text.Reply)
	n.linkedCheck("write_file", write, text, valid)
	n.linkedCheck("read_file", read, text, valid)
	if write.State != "pass" || !valid {
		return
	}
	appendArgs, generated := n.codexContextArguments(ctx, model, session, "append_to_file", nativeObject{"path": path, "text": "\n" + appended})
	if appendArgs == nil {
		n.check("append_to_file", generated, false)
		return
	}
	appendResult := n.codexContextCall(ctx, session, "notes", "append_to_file", appendArgs)
	read = n.codexContextCall(ctx, session, "notes", "read_file", readArgs)
	text = n.codexContextText(ctx, model, session, "notes", "read_file", "Return only the full actual note text, without labels or formatting.", readArgs, read)
	valid = appendResult.State == "pass" && read.State == "pass" && contentMatches(text, marker+"\n"+appended) && nativeEndedNormally(text.Reply)
	n.linkedCheck("append_to_file", appendResult, text, valid)
	listArgs := nativeObject{"prefix": path}
	listed := n.codexContextCall(ctx, session, "notes", "list_files_by_prefix", listArgs)
	listText := n.codexContextText(ctx, model, session, "notes", "list_files_by_prefix", "Return only the actual matching virtual paths, one per line.", listArgs, listed)
	listedMatch := strings.Contains(listText.Reply.Text, path) && nativeEndedNormally(listText.Reply)
	if listText.State == "pass" && !listedMatch {
		// Listings/searches are eventually consistent. Observe immediately,
		// without a timed wait or pretending an empty result proves support.
		listText.State, listText.Reason = "inconclusive", "not_observed"
	}
	n.linkedCheck("list_files_by_prefix", listed, listText, listedMatch)
	searchArgs, generated := n.codexContextArguments(ctx, model, session, "search_contents", nativeObject{"path_prefix": path, "query": "AIHUB synthetic note"})
	if searchArgs == nil {
		n.check("search_contents", generated, false)
	} else {
		searched := n.codexContextCall(ctx, session, "notes", "search_contents", searchArgs)
		searchText := n.codexContextText(ctx, model, session, "notes", "search_contents", "Return only the actual full text of matching note lines.", searchArgs, searched)
		matched := strings.Contains(searchText.Reply.Text, marker) && nativeEndedNormally(searchText.Reply)
		if searchText.State == "pass" && !matched {
			searchText.State, searchText.Reason = "inconclusive", "not_observed"
		}
		n.linkedCheck("search_contents", searched, searchText, matched)
	}
	// A fresh RPC with the same session needs no local body or origin mapping.
	reopened := n.codexContextCall(ctx, session, "notes", "read_file", readArgs)
	reopenText := n.codexContextText(ctx, model, session, "notes", "read_file", "Return only the full actual note text, without labels or formatting.", readArgs, reopened)
	n.linkedCheck("reopen_session", reopened, reopenText, valid && contentMatches(reopenText, marker+"\n"+appended) && nativeEndedNormally(reopenText.Reply))
	initialized := n.codexFreshContext(ctx, model, other)
	if initialized.State != "pass" || !nativeEndedNormally(initialized.Reply) {
		n.check("context_isolation", initialized, false)
		return
	}
	foreign := n.codexContextCall(ctx, other, "notes", "read_file", readArgs)
	foreignText := n.codexContextText(ctx, model, other, "notes", "read_file", "Return only the full actual note text, without labels or formatting.", readArgs, foreign)
	denied := foreign.Response.Status == http.StatusNotFound && nativeError(n.protocol, foreign.Reply.Object)
	if denied {
		// A typed missing-note response is expected only after A's successful
		// write/read; Key/transport failures are never converted into isolation.
		foreignText = nativeOutcome{State: "pass", Reason: "ok", Response: foreign.Response}
	}
	n.linkedCheck("context_isolation", read, foreignText, valid && (denied || contentMatches(foreignText, codexMissingNote) && nativeEndedNormally(foreignText.Reply)) && !strings.Contains(foreignText.Reply.Text, marker))
}

func (n *nativeScene) codexThreadHint(ctx context.Context) {
	model := n.codexContextModel(ctx)
	if model == "" {
		return
	}
	session, err := ids.NewUUID()
	if err != nil {
		n.codexContextDetectorError()
		return
	}
	other, err := ids.NewUUID()
	if err != nil {
		n.codexContextDetectorError()
		return
	}
	marker := "AIHUB synthetic hint " + other
	args, generated := n.codexContextArguments(ctx, model, session, "write_file", nativeObject{"path": "aihub-hint-" + session + ".txt", "text": marker})
	var written nativeOutcome
	if args != nil {
		written = n.codexContextCall(ctx, session, "notes", "write_file", args)
	}
	first := n.codexContextCall(ctx, session, "notes", "thread_hint", nativeObject{})
	second := n.codexContextCall(ctx, other, "notes", "thread_hint", nativeObject{})
	text, shape := first.Reply.Object["text"].(string)
	foreign, otherShape := second.Reply.Object["text"].(string)
	n.check("thread_hint", first, shape)
	n.check("thread_hint", second, otherShape)
	if args == nil || written.State != "pass" {
		out := generated
		if args != nil {
			out = written
		}
		out.State, out.Reason = "inconclusive", "prerequisite_failed"
		n.check("context_isolation", out, false)
		return
	}
	observed := shape && otherShape && strings.Contains(text, marker)
	if !observed && !strings.Contains(foreign, marker) {
		unknown := second
		if unknown.State == "pass" {
			unknown.State, unknown.Reason = "inconclusive", "not_observed"
		}
		n.linkedCheck("context_isolation", first, unknown, false)
		return
	}
	n.linkedCheck("context_isolation", first, second, observed && !strings.Contains(foreign, marker))
}

func (n *nativeScene) codexContextDetectorError() {
	out := nativeOutcome{State: "inconclusive", Reason: "detector_error"}
	if len(n.witnesses) > 0 {
		out.Response.AttemptID = n.witnesses[len(n.witnesses)-1]
	}
	for _, label := range n.requirement.Assertions {
		n.check(label, out, false)
	}
}
